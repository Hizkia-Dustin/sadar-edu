// Penanda lokasi dengan tanda tambah, 7x9.
const PIN_GLYPH = [
  '..###..',
  '.#...#.',
  '#..#..#',
  '#.###.#',
  '#..#..#',
  '.#...#.',
  '.#...#.',
  '..#.#..',
  '...#...',
];

export function DotGlyph({ rows, className = '', animated = false, seed = null }) {
  const cols = rows[0].length;
  let lit = 0;
  return (
    <span className={`dm-glyph ${className}`} style={{ '--cols': cols }} aria-hidden="true">
      {rows.flatMap((row, r) =>
        row.split('').map((cell, c) => {
          const on = cell === '#';
          const order = on ? lit++ : 0;
          return (
            <i
              key={`${r}-${c}`}
              className={on ? 'is-on' : ''}
              style={
                animated && on
                  ? { '--i': order }
                  : seed !== null && on
                    ? { '--r': (r * 7 + c * 13 + seed * 5) % 11 }
                    : undefined
              }
            />
          );
        })
      )}
    </span>
  );
}

export function DotText({ text, className = '', print = false }) {
  return (
    <span className={`dm-text ${className}`} aria-hidden="true">
      {String(text).toUpperCase().split('').map((ch, i) => (
        <DotGlyph key={`${ch}-${i}`} rows={FONT[ch] ?? FONT[' ']} seed={print ? i : null} />
      ))}
    </span>
  );
}

export function DotPin(props) {
  return <DotGlyph rows={PIN_GLYPH} {...props} />;
}
